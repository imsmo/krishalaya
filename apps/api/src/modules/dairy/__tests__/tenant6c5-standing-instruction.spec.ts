describe('THE CAP — the automatic path may never need a human to ask', () => {
  it('is the LOWER of the assembly cap and the consent threshold', () => {
    // This is what makes W169's sentence true rather than aspirational: standing instructions govern below the line,
    // fresh consent above it. If the assembler could cross the line it would produce 312 bills that all need a
    // member's answer before payday — a queue of 312 conversations, generated by software, on a Thursday.
    expect(assemblyCapMinor(400_000n, 25, 25)).toBe(100_000n);
    expect(assemblyCapMinor(400_000n, 40, 25)).toBe(100_000n);   // a loose assembly cap cannot outrun consent
    expect(assemblyCapMinor(400_000n, 10, 25)).toBe(40_000n);    // a kinder cooperative caps itself lower
  });

  it('is zero when either setting is zero, and on a bill worth nothing', () => {
    expect(assemblyCapMinor(400_000n, 0, 25)).toBe(0n);          // assembly switched off by setting
    expect(assemblyCapMinor(400_000n, 25, 0)).toBe(0n);
    expect(assemblyCapMinor(0n, 25, 25)).toBe(0n);
  });

  it('truncates in the MEMBER\'s favour and never touches a float', () => {
    // 33% of 1,001 is 330.33 minor units; the third of a paisa stays with the family.
    expect(assemblyCapMinor(1_001n, 33, 100)).toBe(330n);
    const code = read('../domain/deduction-plan.ts')
      .replace(/\/\*[\s\S]*?\*\//g, '').split('\n').filter((l) => !l.trim().startsWith('//')).join('\n');
    expect(code).not.toMatch(/Number\(|parseFloat|\d\.\d/);
  });

  it('reads BOTH settings and refuses to guess either', async () => {
    const tx = { query: jest.fn().mockResolvedValue({ rows: [{ key: 'dairy.deduction_assembly_max_pct', pct: 25 }] }) };
    const repo = new DairyDeductionInstructionRepository({ forTenant: () => ({ query: jest.fn() }) } as never);
    // Only one of the two came back — a database whose seed did not run. Inventing 100 would let software take a
    // whole fortnight's milk without asking anybody, which is worse than a readable failure (0158's ruling).
    await expect(repo.assemblyPct(tx as never, 'tA')).rejects.toThrow(/dairy\.deduction_consent_pct is missing/);
    // The tenant's OWN override, then the platform default — a join on `ts.tenant_id = $1`. Joining on anything else
    // (the mutation run tried `IS NULL`) would silently ignore a cooperative that had tightened its own cap.
    expect(tx.query.mock.calls[0][0]).toMatch(/COALESCE\(ts\.value, d\.default_value\)/);
    expect(tx.query.mock.calls[0][0]).toMatch(/LEFT JOIN tenant_settings ts ON ts\.key = d\.key AND ts\.tenant_id = \$1/);
  });
});

