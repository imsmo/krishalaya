describe('THE ASSEMBLER — only what the member arranged', () => {
  const feedType = { id: 'lv-feed', code: 'feed_credit', name: 'Feed', destination: 'member_credit' as const, unsupportedReason: null, sourceType: 'dairy_member_credit' };
  const loanType = { id: 'lv-loan', code: 'loan_emi', name: 'Loan', destination: 'loan' as const, unsupportedReason: null, sourceType: 'loan' };
  const credit = (id: string, value: bigint, issuedOn: string) => DairyMemberCredit.rehydrate({
    id, tenantId: 'tA', membershipId: 'mem1', mccId: null, description: 'feed', valueMinor: value,
    recoveredMinor: 0n, issuedOn, issuedBy: 'op1', status: 'outstanding' });
  const instruction = (over: Partial<{ typeId: string; typeCode: string; sourceId: string | null; maxPerCycleMinor: bigint | null }> = {}) =>
    DairyDeductionInstruction.authorise({
      id: `i-${over.typeId ?? 'lv-feed'}-${over.sourceId ?? 'all'}`, tenantId: 'tA', membershipId: 'mem1',
      typeId: over.typeId ?? 'lv-feed', typeCode: over.typeCode ?? 'feed_credit',
      sourceId: over.sourceId ?? null, maxPerCycleMinor: over.maxPerCycleMinor ?? null,
      authorisedBy: 'farmer1', authorisedAt: NOW, channel: 'app', assistedBy: null, recordedBy: 'farmer1', note: null , notice: { what: { en: 'feed credit' }, how_much: { en: 'INR 200.00' } } });

  function harness(over: { live?: unknown[]; credits?: unknown[]; loans?: unknown[]; pct?: { assemblyPct: number; consentPct: number } } = {}) {
    const instructions = {
      activeForMembership: jest.fn(async () => over.live ?? []),
      assemblyPct: jest.fn(async () => over.pct ?? { assemblyPct: 25, consentPct: 25 }),
    };
    const credits = { listOutstanding: jest.fn(async () => over.credits ?? []) };
    const types = { list: jest.fn(async () => [feedType, loanType]) };
    const memberships = { getById: jest.fn(async () => ({ id: 'mem1', farmerUserId: 'farmer1' })) };
    const loans = { milkDeductibleLoans: jest.fn(async () => over.loans ?? []) };
    const svc = new DairyDeductionAssemblerService(instructions as never, credits as never, types as never, memberships as never, loans as never);
    return { svc, instructions, credits, loans, memberships };
  }
  const tx = { query: jest.fn() } as never;

  it('assembles NOTHING for a member with no arrangement — their whole cheque is theirs', async () => {
    const h = harness({ credits: [credit('credit1', 50_000n, '2026-07-01')] });
    const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(plan.lines).toEqual([]);
    // And it does not even ask for the debts: no arrangement, nothing to plan.
    expect(h.credits.listOutstanding).not.toHaveBeenCalled();
  });

  it('recovers an outstanding credit the member arranged', async () => {
    const h = harness({ live: [instruction()], credits: [credit('credit1', 50_000n, '2026-07-01')] });
    const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(plan.lines).toEqual([expect.objectContaining({ typeCode: 'feed_credit', sourceType: 'dairy_member_credit', sourceId: 'credit1', amountMinor: 50_000n })]);
  });

  it('does NOT recover a debt the member did not arrange, even with a blanket arrangement of another type', async () => {
    const h = harness({ live: [instruction({ typeId: 'lv-loan', typeCode: 'loan_emi' })], credits: [credit('credit1', 50_000n, '2026-07-01')] });
    const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(plan.lines).toEqual([]);
    // A loan arrangement does not authorise recovering feed. This is the whole difference between "authorised" and
    // "automatic", and it is the reason the assembler reads instructions before it reads debts.
  });

  it('a SOURCE-SPECIFIC arrangement wins over the blanket one', async () => {
    // A member who said "₹200 a fortnight on THAT credit" has said something more precise than "recover my credits",
    // and honouring the general rule over the specific one would take more than they agreed to.
    const h = harness({
      live: [instruction(), instruction({ sourceId: 'credit1', maxPerCycleMinor: 20_000n })],
      credits: [credit('credit1', 50_000n, '2026-07-01'), credit('credit2', 30_000n, '2026-07-02')],
    });
    const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(plan.lines).toEqual([
      expect.objectContaining({ sourceId: 'credit1', amountMinor: 20_000n }),
      expect.objectContaining({ sourceId: 'credit2', amountMinor: 30_000n }),
    ]);
  });

  it('does NOT recover a LOAN the member did not arrange, even with an arrangement for another loan', async () => {
    // The loan mirror of the credit case above, and the mutation run's proof that it was needed: falling back to
    // "any loan arrangement will do" would recover loan B on the strength of an instalment agreed for loan A.
    const h = harness({
      live: [instruction({ typeId: 'lv-loan', typeCode: 'loan_emi', sourceId: 'loanA', maxPerCycleMinor: 10_000n })],
      loans: [{ id: 'loanB', outstandingMinor: 200_000n, disbursedAt: '2026-04-01', status: 'active' }],
    });
    expect((await h.svc.assemble(tx, 'tA', 'mem1', 400_000n)).lines).toEqual([]);
  });

  it('LOGS a capped recovery rather than leaving it to be inferred', async () => {
    const spy = jest.spyOn(Logger.prototype, 'log').mockImplementation(() => undefined);
    try {
      const h = harness({ live: [instruction()], credits: [credit('credit1', 5_000_000n, '2026-07-01')] });
      const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
      expect(plan.deferred).toHaveLength(1);
      // TENANT-6c-1's ruling about stranded pours, applied: a partial recovery is a real outcome, and an outcome
      // nobody can see is indistinguishable from arithmetic that does not add up.
      expect(spy).toHaveBeenCalledWith(expect.stringContaining('deferred to the next cycle'));
    } finally { spy.mockRestore(); }
  });

  it('reads LOANS through the fintech module\'s public service, by the member\'s user id', async () => {
    const h = harness({
      live: [instruction({ typeId: 'lv-loan', typeCode: 'loan_emi' })],
      loans: [{ id: 'loan1', outstandingMinor: 200_000n, disbursedAt: '2026-04-01', status: 'active' }],
    });
    const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(h.loans.milkDeductibleLoans).toHaveBeenCalledWith(tx, 'tA', 'farmer1');
    expect(plan.lines).toEqual([expect.objectContaining({ typeCode: 'loan_emi', sourceType: 'loan', sourceId: 'loan1', amountMinor: 100_000n })]);
    // Capped at 25% of the gross even though ₹2,000 is outstanding — the automatic path stops at the line.
    expect(plan.capMinor).toBe(100_000n);
    const src = read('../services/dairy-deduction-assembler.service.ts');
    expect(src).toMatch(/from '\.\.\/\.\.\/fintech\/services\/loan\.service'/);
    expect(src).not.toMatch(/fintech\/repositories/);
  });

  it('does not ask the other module anything when no LOAN arrangement exists', async () => {
    const h = harness({ live: [instruction()], credits: [] });
    await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(h.loans.milkDeductibleLoans).not.toHaveBeenCalled();
  });

  it('assembles nothing when the tenant has set its cap to zero', async () => {
    const h = harness({ live: [instruction()], credits: [credit('credit1', 50_000n, '2026-07-01')], pct: { assemblyPct: 0, consentPct: 25 } });
    const plan = await h.svc.assemble(tx, 'tA', 'mem1', 400_000n);
    expect(plan.lines).toEqual([]);
    expect(h.credits.listOutstanding).not.toHaveBeenCalled();
  });
});

