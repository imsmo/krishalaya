describe('THE PLAN — oldest debt first, and nothing hidden', () => {
  it('takes the whole outstanding when the cap can carry it', () => {
    const plan = planDeductions(400_000n, 100_000n, [candidate({ outstandingMinor: 50_000n })]);
    expect(plan.lines).toEqual([expect.objectContaining({ sourceId: 'credit1', amountMinor: 50_000n })]);
    expect(plan.totalMinor).toBe(50_000n);
    expect(plan.deferred).toEqual([]);
  });

  it('honours the member\'s INSTALMENT over the debt', () => {
    // The humane case, and the one thing no other table can express: "₹200 a fortnight, not the whole ₹500 at once".
    const plan = planDeductions(400_000n, 100_000n, [candidate({ outstandingMinor: 50_000n, maxPerCycleMinor: 20_000n })]);
    expect(plan.totalMinor).toBe(20_000n);
    expect(plan.deferred).toEqual([]);   // taking the agreed instalment is not a deferral
  });

  it('recovers the OLDEST debt first, across types, and never by size or by whose debt it is', () => {
    // Recovering a bank's loan before the cooperative's own feed shop — or the reverse — is a policy W169 does not
    // state, and choosing one silently would decide whose debt a family pays first. Oldest-first is the one order
    // that needs no justification; 0161's header names the per-type priority it does not build.
    // THE OLDER DEBT IS THE SMALLER ONE, deliberately: the first version of this fixture made the oldest debt also
    // the largest, so "largest first" produced the same answer and a mutation run walked straight through it.
    const plan = planDeductions(400_000n, 60_000n, [
      candidate({ id: 'loan1', sourceId: 'loan1', sourceType: 'loan', typeId: 'lv-loan', typeCode: 'loan_emi', outstandingMinor: 40_000n, since: '2026-04-01' }),
      candidate({ id: 'credit1', sourceId: 'credit1', outstandingMinor: 500_000n, since: '2026-07-01' }),
    ]);
    expect(plan.lines).toEqual([
      expect.objectContaining({ sourceId: 'loan1', amountMinor: 40_000n }),      // oldest, in full
      expect.objectContaining({ sourceId: 'credit1', amountMinor: 20_000n }),    // then whatever the cap has left
    ]);
    expect(plan.deferred).toEqual([
      { sourceType: 'dairy_member_credit', sourceId: 'credit1', wantedMinor: 500_000n, takenMinor: 20_000n },
    ]);
  });

  it('breaks a same-day tie on the id, so two runs of the same fortnight agree', () => {
    const plan = planDeductions(400_000n, 30_000n, [
      candidate({ id: 'b', sourceId: 'b', outstandingMinor: 30_000n, since: '2026-07-01' }),
      candidate({ id: 'a', sourceId: 'a', outstandingMinor: 30_000n, since: '2026-07-01' }),
    ]);
    expect(plan.lines[0].sourceId).toBe('a');
  });

  it('takes a debt PARTLY rather than skipping it — and reports what it could not take', () => {
    // A family with one big debt would otherwise have nothing recovered for ever and the cooperative's books would
    // never move. What must not happen is the partial take being invisible.
    const plan = planDeductions(400_000n, 40_000n, [candidate({ outstandingMinor: 500_000n })]);
    expect(plan.totalMinor).toBe(40_000n);
    expect(plan.deferred).toEqual([{ sourceType: 'dairy_member_credit', sourceId: 'credit1', wantedMinor: 500_000n, takenMinor: 40_000n }]);
  });

  it('never exceeds its cap, however many arrangements there are', () => {
    const many = Array.from({ length: 20 }, (_, i) => candidate({ id: `c${i}`, sourceId: `c${i}`, outstandingMinor: 30_000n, since: `2026-07-${String(i + 1).padStart(2, '0')}` }));
    const plan = planDeductions(400_000n, 100_000n, many);
    expect(plan.totalMinor).toBe(100_000n);
    expect(plan.lines.reduce((a, l) => a + l.amountMinor, 0n)).toBe(100_000n);
    expect(plan.lines.length).toBe(4);   // three whole and one part
  });

  it('REFUSES a cap bigger than the gross rather than trusting its caller', () => {
    // The invariant the file exists for. A caller that computed the cap wrongly (or read the wrong setting) would
    // otherwise build 312 bills whose deductions exceed their gross, and the aggregate would refuse them one at a
    // time on payday. Better to stop here, loudly.
    expect(() => planDeductions(100n, 1_000n, [candidate({ outstandingMinor: 500n })])).toThrow(/overran its cap/);
  });

  it('applies the cap to the TOTAL, not to each line', () => {
    // `remaining -= take` is what makes the cap a budget rather than a per-line limit; without it three ₹400 debts
    // would take ₹1,200 against a ₹500 cap.
    const plan = planDeductions(400_000n, 50_000n, [
      candidate({ id: 'a', sourceId: 'a', outstandingMinor: 40_000n, since: '2026-07-01' }),
      candidate({ id: 'b', sourceId: 'b', outstandingMinor: 40_000n, since: '2026-07-02' }),
    ]);
    expect(plan.totalMinor).toBe(50_000n);
    expect(plan.lines.map((l) => l.amountMinor)).toEqual([40_000n, 10_000n]);
  });

  it('takes nothing at all when the cap is zero, and skips a settled debt', () => {
    expect(planDeductions(400_000n, 0n, [candidate()]).lines).toEqual([]);
    expect(planDeductions(400_000n, 100_000n, [candidate({ outstandingMinor: 0n })]).lines).toEqual([]);
  });
});

