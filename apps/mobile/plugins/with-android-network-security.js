// apps/mobile/plugins/with-android-network-security.js · PC-56 MOB-TLS-1 — Expo config plugin that makes Android's network
// security policy EXPLICIT instead of relying on platform defaults:
//   • release (src/main): cleartext forbidden + trust ONLY the system CA store. User-installed CAs (what a corporate/ISP MITM
//     proxy or an attacker's "install this profile" asks for) are not trusted. This is already Android's default for apps
//     targeting API 24+ — written out so a future targetSdk/library change cannot silently re-open it, and so it is reviewable.
//   • debug (src/debug resource overlay — only the `debug` build type, i.e. `expo run:android` / the EAS `development`
//     profile): cleartext allowed (Metro on http://<LAN-IP>:8081, a local API) and user CAs trusted (dev proxies).
// The public-key pins themselves are NOT here: they are installed at runtime by react-native-ssl-public-key-pinning
// (src/core/security/tls-pinning.runtime.ts) so a pin mismatch can be reported to Sentry — a <pin-set> in this file would
// reject the handshake first and the failure would be invisible. See docs/mobile/TLS-PINNING.md.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');

const RESOURCE = 'network_security_config';

function releaseNetworkSecurityXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/with-android-network-security.js (MOB-TLS-1). Release: HTTPS only, system CAs only. -->',
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="false">',
    '    <trust-anchors>',
    '      <certificates src="system" />',
    '    </trust-anchors>',
    '  </base-config>',
    '</network-security-config>',
    '',
  ].join('\n');
}

function debugNetworkSecurityXml() {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/with-android-network-security.js (MOB-TLS-1). DEBUG build type only: Metro over http + dev proxies. -->',
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="true">',
    '    <trust-anchors>',
    '      <certificates src="system" />',
    '      <certificates src="user" />',
    '    </trust-anchors>',
    '  </base-config>',
    '</network-security-config>',
    '',
  ].join('\n');
}

function writeXml(projectRoot, sourceSet, xml) {
  const dir = path.join(projectRoot, 'android', 'app', 'src', sourceSet, 'res', 'xml');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `${RESOURCE}.xml`), xml);
}

function withAndroidNetworkSecurity(config) {
  config = withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = `@xml/${RESOURCE}`;
    return cfg;
  });
  return withDangerousMod(config, ['android', (cfg) => {
    writeXml(cfg.modRequest.projectRoot, 'main', releaseNetworkSecurityXml());
    writeXml(cfg.modRequest.projectRoot, 'debug', debugNetworkSecurityXml());
    return cfg;
  }]);
}

module.exports = withAndroidNetworkSecurity;
module.exports.releaseNetworkSecurityXml = releaseNetworkSecurityXml;
module.exports.debugNetworkSecurityXml = debugNetworkSecurityXml;
