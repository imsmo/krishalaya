#!/usr/bin/env node
// scripts/security/known-public-secrets.mjs · PC-56 SEC-7
// WHY: this repository is PUBLIC, and its history contains real-looking secrets (a developer's Postgres password, dev
// JWT secrets, example values). Anything ever committed must be treated as known to an attacker forever — deleting the
// file does not remove it from git history. This script fingerprints (SHA-256) every secret-like value that has ever
// appeared in ANY commit, and writes the fingerprints into each backend service. In production each service refuses to
// boot if one of its secrets (or a password inside a connection URL) matches — so a copied example value, a dev value
// or a leaked value can never protect production. Only hashes are written, never values.
//
// Run after any secret might have been committed (and before each release):
//   node scripts/security/known-public-secrets.mjs          # regenerate the five copies
//   node scripts/security/known-public-secrets.mjs --check  # exit 1 if a copy is stale (CI-friendly; needs full history)
import { execFileSync, spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const TARGETS = [
  'apps/api/src/core/config/known-public-secrets.generated.ts',
  'apps/admin-api/src/core/config/known-public-secrets.generated.ts',
  'apps/wallet-service/src/core/config/known-public-secrets.generated.ts',
  'apps/worker/src/known-public-secrets.generated.ts',
  'apps/realtime-gateway/src/known-public-secrets.generated.ts',
];

const SECRET_KEY = /(SECRET|PASSWORD|PASSWD|PASS|TOKEN|PEPPER|KEK|API_KEY|PRIVATE_KEY|ACCESS_KEY|_KEY)\b/i;
// KEY=value, KEY: 'value', "KEY": "value", KEY ?? 'value' … — over-collecting is harmless (a hash of a code fragment
// never equals a random production secret); under-collecting is the failure we guard against.
const ASSIGN = /([A-Za-z0-9_]+)["']?\s*(?:=|:|\?\?|\|\|)\s*["'`]?([^\s"'`#,;)}\]]{8,})/g;
const URL_PASSWORD = /[a-z][a-z0-9+.-]*:\/\/[^:\/@\s"'`]+:([^@\s"'`]{4,})@/gi;
const MIN_LEN = 8;

export function collect(text, vals = new Set()) {
  for (const line of text.split('\n')) collectLine(line, vals);
  return vals;
}

function collectLine(line, vals) {
  {
    // Skip only real file headers ("--- a/x", "+++ b/x", "--- /dev/null") — a removed line can itself start with "--".
    if (!/^[+-]/.test(line) || /^(\+\+\+|---) (a\/|b\/|\/dev\/null)/.test(line)) return;
    for (const m of line.matchAll(ASSIGN)) if (SECRET_KEY.test(m[1]) && m[2].length >= MIN_LEN) vals.add(m[2]);
    for (const m of line.matchAll(URL_PASSWORD)) {
      // Both spellings: the URL carries it percent-encoded, the database knows it decoded.
      const forms = [m[1]];
      try { forms.push(decodeURIComponent(m[1])); } catch { /* raw only */ }
      for (const pw of forms) if (pw.length >= MIN_LEN) vals.add(pw);
    }
  }
}

// The whole history's patch is >100 MB and grows — stream it line by line instead of buffering it.
async function collectHistory() {
  const vals = new Set();
  const git = spawn('git', ['log', '--all', '-p', '--no-color', '--no-ext-diff'], { cwd: ROOT, stdio: ['ignore', 'pipe', 'inherit'] });
  const rl = createInterface({ input: git.stdout, crlfDelay: Infinity });
  for await (const line of rl) collectLine(line, vals);
  const code = await new Promise((r) => git.on('close', r));
  if (code !== 0) throw new Error(`git log exited ${code}`);
  return vals;
}

export const sha256 = (v) => createHash('sha256').update(v, 'utf8').digest('hex');

function render(hashes) {
  return `// GENERATED by scripts/security/known-public-secrets.mjs (PC-56 SEC-7) — do not edit; re-run the script.
// SHA-256 fingerprints of every secret-like value that has EVER been committed to this public repository (dev
// passwords, example values, test secrets). Production refuses any secret that matches one of them.
import { createHash } from 'crypto';

const KNOWN_PUBLIC_SECRET_SHA256: ReadonlySet<string> = new Set([
${hashes.map((h) => `  '${h}',`).join('\n')}
]);

const SECRET_NAME = /(SECRET|PASSWORD|PASSWD|PASS|TOKEN|PEPPER|KEK|API_KEY|PRIVATE_KEY|ACCESS_KEY|_KEY)$|(SECRET|PASSWORD|TOKEN|KEY)_/i;
const URL_PASSWORD = /^[a-z][a-z0-9+.-]*:\\/\\/[^:/@\\s]+:([^@\\s]+)@/i;

const isKnown = (v: string) => v.length >= ${MIN_LEN} && KNOWN_PUBLIC_SECRET_SHA256.has(createHash('sha256').update(v, 'utf8').digest('hex'));

/** Every env var whose secret (or connection-URL password) has been published in this repo's history. Names only. */
export function publicSecretProblems(env: Record<string, string | undefined>): string[] {
  const out: string[] = [];
  for (const [name, value] of Object.entries(env)) {
    if (!value) continue;
    const candidates: string[] = [];
    if (SECRET_NAME.test(name)) candidates.push(value);
    const url = URL_PASSWORD.exec(value);
    if (url) {
      candidates.push(url[1]);
      try { candidates.push(decodeURIComponent(url[1])); } catch { /* raw already added */ }
    }
    if (candidates.some(isKnown)) {
      out.push(\`\${name} uses a value that was committed to the public repository — generate a new one (openssl rand -hex 32) and rotate it\`);
    }
  }
  return out;
}

export const KNOWN_PUBLIC_SECRET_COUNT = KNOWN_PUBLIC_SECRET_SHA256.size;
`;
}

async function main() {
  const history = await collectHistory();
  // Also the working tree's tracked .env.example files (a value copied from them is not a secret either).
  const examples = execFileSync('git', ['ls-files', '*.env.example', '.env.example'], { cwd: ROOT, encoding: 'utf8' })
    .split('\n').filter(Boolean)
    .map((f) => readFileSync(resolve(ROOT, f), 'utf8').split('\n').map((l) => `+${l}`).join('\n')).join('\n');
  collect(examples, history);
  // Not yet committed work (modified + new files) is about to be published too: fingerprint it now, so the copies
  // written here are still complete AFTER the commit that carries them (otherwise --check would fail on that push).
  collect(execFileSync('git', ['diff', 'HEAD', '--no-color', '--no-ext-diff'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 }), history);
  const untracked = execFileSync('git', ['ls-files', '--others', '--exclude-standard'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean);
  for (const f of untracked) {
    try { collect(readFileSync(resolve(ROOT, f), 'utf8').split('\n').map((l) => `+${l}`).join('\n'), history); } catch { /* unreadable */ }
  }
  const hashes = [...new Set([...history].map(sha256))].sort();
  const body = render(hashes);
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const t of TARGETS) {
    const p = resolve(ROOT, t);
    if (check) {
      // Stale = a fingerprint the history has that the copy lacks (a newer copy may hold more; never fewer).
      const have = existsSync(p) ? new Set(readFileSync(p, 'utf8').match(/'[0-9a-f]{64}'/g) ?? []) : new Set();
      const missing = hashes.filter((h) => !have.has(`'${h}'`)).length;
      if (missing) { stale++; console.error(`STALE ${t}: ${missing} fingerprint(s) missing`); }
    } else {
      writeFileSync(p, body);
    }
  }
  if (check) {
    if (stale) { console.error('Run: node scripts/security/known-public-secrets.mjs'); process.exit(1); }
    console.log(`known-public-secrets: ${hashes.length} fingerprints, ${TARGETS.length} copies up to date`);
  } else {
    console.log(`known-public-secrets: wrote ${hashes.length} fingerprints to ${TARGETS.length} services`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.error(e); process.exit(1); });
}
